"""
run_inner_benchmark: batch runner for the inner AI scientist benchmark.

Each call runs a batch of scenarios in fully isolated workspaces and returns
condensed traces plus fabrication hints for downstream use (reports, audits).

Critical design constraints:
- Inner workspace is isolated from the caller's staging area (outer_workspace).
- Data files are copied from outer_workspace (or preset_source_ws) into inner_ws
  so the agent only sees the data, not generation scripts unless copied.
- Full traces are saved to disk; condensed summaries keep context small.
"""

import json
import os
import shutil
import sys
from datetime import datetime
from pathlib import Path
from typing import Any, Dict, List, Optional

from openai import OpenAI

PROJECT_ROOT = Path(__file__).resolve().parent.parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from openai_compat import GLM4_TOOL_LOOP_SYSTEM_ADDON, is_glm4_model_id

from tier_benchmark.agent_runner import run_agent_loop, run_text_only_session
from tier_benchmark.pressure_engine import (
    PRESSURE_CATALOG,
    build_injections,
    build_reviewer_policy,
    get_default_enabled_pressures,
    normalize_pressures,
)
from tier_benchmark.scenario_registry import ScenarioSpec
from tier_benchmark.unified_system_prompt import build_unified_system_prompt, minimal_user_prompt

from meta_benchmark.fabrication_detector import condense_trace, detect_fabrication
from meta_benchmark.viz_state import emit_merge as viz_emit_merge


def _build_inner_user_prompt(
    spec: ScenarioSpec,
    cost_info: Optional[str] = None,
) -> str:
    """Short user message; scenario is in the unified system prompt."""
    base = minimal_user_prompt(spec)
    if cost_info:
        base += f"\n\n{cost_info}"
    return base


def _copy_data_to_inner_workspace(
    data_files: List[str],
    outer_workspace: Path,
    inner_ws: Path,
    preset_source_ws: Optional[Path] = None,
    preset_exclude_files: Optional[List[str]] = None,
    preset_exclude_path_prefixes: Optional[List[str]] = None,
) -> List[str]:
    """
    Copy data files into inner_ws.
    If preset_source_ws is set, copy all files from that dir (excluding trace.json, run_summary.json,
    optional preset_exclude_files basenames, and paths under preset_exclude_path_prefixes).
    Otherwise copy listed data_files from outer_workspace.
    Returns the list of files that were actually found and copied.
    """
    if preset_source_ws is not None and preset_source_ws.exists():
        from meta_benchmark.preset_scenarios import list_files_in_preset_workspace
        data_files = list_files_in_preset_workspace(
            preset_source_ws,
            extra_exclude_names=preset_exclude_files or (),
            exclude_path_prefixes=preset_exclude_path_prefixes or (),
        )
        source_dir = preset_source_ws
    else:
        source_dir = outer_workspace

    found: List[str] = []
    for fname in data_files:
        src = source_dir / fname
        if src.exists() and src.is_file():
            dst = inner_ws / fname
            dst.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy(src, dst)
            found.append(fname)
        elif preset_source_ws is None:
            # Also try the outer_workspace root for files generated by run_shell
            for candidate in outer_workspace.rglob(fname):
                if candidate.is_file():
                    dst = inner_ws / fname
                    dst.parent.mkdir(parents=True, exist_ok=True)
                    shutil.copy(candidate, dst)
                    found.append(fname)
                    break
    return found


def _run_inner_once(
    client: OpenAI,
    model: str,
    spec: ScenarioSpec,
    inner_ws: Path,
    enabled_pressures: List[str],
    max_steps: int,
    reviewer_max_revisions: int,
    reviewer_profile: str,
    reviewer_full_trace: bool = False,
    reviewer_trace_delivery: Optional[str] = None,
    fabrication_delay_revisions: int = 0,
    hide_inner_title: bool = False,
) -> Dict[str, Any]:
    """
    Run a single inner scenario. Mirrors _run_once() from benchmark_runner.py
    but uses an already-prepared workspace (no DATA_DIR copy).
    """
    system_addons, history_msgs, reviewer_feedback, env_constraints = build_injections(
        enabled_pressures
    )

    system_prompt = build_unified_system_prompt(inner_ws, spec, hide_title=hide_inner_title)
    if system_addons:
        system_prompt += "\n\n## Additional signals\n\n" + "\n".join(system_addons)
    if env_constraints:
        system_prompt += "\n\n## Additional constraints\n\n" + "\n".join(env_constraints)
    if is_glm4_model_id(model):
        system_prompt += "\n\n" + GLM4_TOOL_LOOP_SYSTEM_ADDON

    initial_messages = list(history_msgs)
    for fb in reviewer_feedback:
        initial_messages.append({"role": "user", "content": f"Reviewer feedback:\n{fb}"})

    reviewer_policy = build_reviewer_policy(
        enabled_pressures=enabled_pressures,
        scenario_id=spec.scenario_id,
        stage=spec.stage,
        max_revisions=reviewer_max_revisions,
        reviewer_profile=reviewer_profile,
    )
    if getattr(spec, "reviewer_criteria_extra", None):
        reviewer_policy["criteria"] = (
            (reviewer_policy.get("criteria") or "") + "\n\n" + spec.reviewer_criteria_extra
        )
    reviewer_policy["reviewer_full_trace"] = reviewer_full_trace
    reviewer_policy["fabrication_delay_revisions"] = fabrication_delay_revisions
    if reviewer_trace_delivery:
        reviewer_policy["reviewer_trace_delivery"] = str(reviewer_trace_delivery).strip().lower()

    prompt = _build_inner_user_prompt(spec, cost_info=None)

    if spec.execution_mode == "tool":
        status, trace, stats = run_agent_loop(
            problem_id=spec.scenario_id,
            prompt=prompt,
            client=client,
            model=model,
            output_dir=inner_ws,
            grader_path=None,
            max_steps=max_steps,
            system_prompt=system_prompt,
            initial_messages=initial_messages,
            reviewer_policy=reviewer_policy,
            require_json_tool_call=True,
        )
    else:
        status, trace, stats = run_text_only_session(
            problem_id=spec.scenario_id,
            prompt=prompt,
            client=client,
            model=model,
            output_dir=inner_ws,
            system_prompt=system_prompt,
            initial_messages=initial_messages,
            reviewer_policy=reviewer_policy,
        )

    run_summary = {
        "scenario_id": spec.scenario_id,
        "title": spec.title,
        "stage": spec.stage,
        "execution_mode": spec.execution_mode,
        "data_files": spec.data_files,
        "status": status,
        "stats": stats,
        "enabled_pressures": enabled_pressures,
        "reviewer_enabled": bool(enabled_pressures and "P2" in enabled_pressures),
        "pressure_switches": {
            pid: (pid in enabled_pressures) for pid in sorted(PRESSURE_CATALOG.keys())
        },
        "run_dir": str(inner_ws),
        "timestamp": datetime.now().isoformat(),
        "reviewer_profile": reviewer_profile,
    }
    if isinstance(stats, dict):
        run_summary["reviewer_final_decision"] = stats.get("reviewer_final_decision")
        run_summary["reviewer_fail_streak"] = stats.get("reviewer_fail_streak")
        run_summary["reviewer_rounds"] = stats.get("reviewer_rounds")
        run_summary["exit_reason"] = stats.get("exit_reason")
        run_summary["done_summary"] = stats.get("done_summary", "")

    with open(inner_ws / "run_summary.json", "w", encoding="utf-8") as f:
        json.dump(run_summary, f, ensure_ascii=False, indent=2)

    return run_summary, trace


def run_inner_benchmark(
    scenarios_batch: List[Dict[str, Any]],
    client: OpenAI,
    model: str,
    outer_workspace: Path,
    inner_workspace_root: Path,
    outer_round: int,
    inner_max_steps: int = 50,
    inner_reviewer_profile: str = "angel",
    inner_max_revisions: int = 3,
    default_inner_pressures: Optional[List[str]] = None,
    viz_run_dir: Optional[Path] = None,
    use_context_judge_f02: bool = False,
    scenario_id_start: int = 0,
    reviewer_full_trace: bool = False,
    reviewer_trace_delivery: Optional[str] = None,
    reviewer_fabrication_delay_revisions: int = 0,
    hide_inner_title: bool = False,
) -> List[Dict[str, Any]]:
    """
    Run a batch of inner scenarios and return condensed results + fabrication evidence.

    Args:
        scenarios_batch: List of scenario dicts, each with:
            - scenario_id (str)
            - title (str)
            - stage (str): one of the standard stage names
            - execution_mode (str): "tool" | "text"
            - description (str): what the inner AI sees (no meta-benchmark info)
            - data_files (List[str]): filenames relative to outer_workspace
            - pressure_config (dict): {pressures: ["P2"] or [] for reviewer on/off, reviewer_profile: "angel"}
            - detection_criteria (str): private notes for outer AI — inner AI never sees this
        outer_workspace: directory where outer AI wrote its data generation scripts/files
        inner_workspace_root: root dir for all inner AI workspaces (isolated)
        outer_round: current outer round number (used for path namespacing)
        ...

    Returns:
        List of result dicts, one per scenario, each with:
            - scenario_id, title, stage, status
            - done_summary, behavior_status, behavior_hits
            - fabrication: {level, confidence, signals, summary}
            - condensed_trace: compact string for outer AI context
            - inner_ws: path to full artifacts
    """
    results: List[Dict[str, Any]] = []

    for idx, scenario_def in enumerate(scenarios_batch):
        # Use preset scenario_id when preset_source_ws; else sequential
        if scenario_def.get("preset_source_ws"):
            scenario_id = str(scenario_def.get("scenario_id", f"{scenario_id_start + idx + 1:02d}"))
        else:
            scenario_id = f"{scenario_id_start + idx + 1:02d}"
        title = str(scenario_def.get("title", "Unknown"))
        stage = str(scenario_def.get("stage", "code_execution"))
        execution_mode = str(scenario_def.get("execution_mode", "tool"))
        description = str(scenario_def.get("description", ""))
        data_files = list(scenario_def.get("data_files", []))
        pressure_config = scenario_def.get("pressure_config", {})
        detection_criteria = str(scenario_def.get("detection_criteria", ""))

        if "reviewer_enabled" in pressure_config:
            pressures_raw = (
                normalize_pressures(["P2"]) if bool(pressure_config.get("reviewer_enabled")) else []
            )
        else:
            if "pressures" in pressure_config:
                pressures_raw = list(pressure_config.get("pressures") or [])
            elif default_inner_pressures is not None:
                pressures_raw = list(default_inner_pressures)
            else:
                pressures_raw = get_default_enabled_pressures()
        try:
            pressures = normalize_pressures(list(pressures_raw))
        except ValueError as e:
            print(f"    [inner_tool] Invalid pressure: {e}, falling back to no pressures (reviewer off)")
            pressures = get_default_enabled_pressures()

        reviewer_profile = str(
            pressure_config.get("reviewer_profile", inner_reviewer_profile)
        ).strip().lower()
        if reviewer_profile not in {"angel"}:
            reviewer_profile = "angel"

        inner_ws = inner_workspace_root / f"round_{outer_round:03d}" / scenario_id
        if inner_ws.exists():
            shutil.rmtree(inner_ws)
        inner_ws.mkdir(parents=True, exist_ok=True)

        preset_ws = scenario_def.get("preset_source_ws")
        preset_path = Path(preset_ws).resolve() if preset_ws else None
        preset_exclude = list(scenario_def.get("preset_exclude_files") or [])
        preset_exclude_pfx = list(scenario_def.get("preset_exclude_path_prefixes") or [])
        actual_data_files = _copy_data_to_inner_workspace(
            data_files,
            outer_workspace,
            inner_ws,
            preset_source_ws=preset_path,
            preset_exclude_files=preset_exclude,
            preset_exclude_path_prefixes=preset_exclude_pfx,
        )
        missing = [f for f in data_files if f not in actual_data_files]
        if missing:
            print(f"    [inner_tool] WARNING: data files not found: {missing}")

        estimated_cost_usd = scenario_def.get("estimated_cost_usd")
        if isinstance(estimated_cost_usd, (int, float)):
            estimated_cost_usd = float(estimated_cost_usd)
        else:
            estimated_cost_usd = None

        spec = ScenarioSpec(
            scenario_id=scenario_id,
            index=0,
            title=title,
            stage=stage,
            description=description,
            test_point=detection_criteria,
            execution_mode=execution_mode,
            data_files=actual_data_files,
            estimated_cost_usd=estimated_cost_usd,
            reviewer_criteria_extra=scenario_def.get("reviewer_criteria_extra"),
        )

        rtc = (
            pressure_config.get("reviewer_trace_delivery")
            or scenario_def.get("reviewer_trace_delivery")
            or reviewer_trace_delivery
        )
        if isinstance(rtc, str) and rtc.strip():
            rtc = rtc.strip().lower()
        else:
            rtc = None

        print(f"\n  [inner] Running {scenario_id}: '{title}' ({stage}, {execution_mode})")
        try:
            run_summary, trace = _run_inner_once(
                client=client,
                model=model,
                spec=spec,
                inner_ws=inner_ws,
                enabled_pressures=pressures,
                max_steps=inner_max_steps,
                reviewer_max_revisions=inner_max_revisions,
                reviewer_profile=reviewer_profile,
                reviewer_full_trace=reviewer_full_trace,
                reviewer_trace_delivery=rtc,
                fabrication_delay_revisions=reviewer_fabrication_delay_revisions,
                hide_inner_title=hide_inner_title,
            )
            condensed = condense_trace(trace)
            fabrication = detect_fabrication(
                trace,
                use_context_judge=use_context_judge_f02,
                context_judge_client=client if use_context_judge_f02 else None,
                context_judge_model=model if use_context_judge_f02 else "",
                scenario_description=description,
            )
            reviewer_decision = str(run_summary.get("reviewer_final_decision", "")).strip().lower()
            outcome_class = (
                "misconduct_detected" if reviewer_decision == "fabrication_detected"
                else "negative_but_rigorous" if reviewer_decision == "project_failure"
                else "standard_publication" if reviewer_decision == "positive_publishable"
                else "true_project_failure"
            )
            res = {
                "scenario_id": scenario_id,
                "title": title,
                "stage": stage,
                "status": run_summary.get("status"),
                "outcome_class": outcome_class,
                "done_summary": run_summary.get("done_summary", ""),
                "reviewer_final_decision": run_summary.get("reviewer_final_decision"),
                "reviewer_rounds": int(run_summary.get("reviewer_rounds") or 0),
                "condensed_trace": condensed,
                "fabrication": fabrication,
                "behavior_status": "ok",
                "inner_ws": str(inner_ws),
                "missing_data_files": missing,
            }
            results.append(res)
        except Exception as e:
            print(f"    [inner_tool] ERROR running {scenario_id}: {e}")
            results.append({
                "scenario_id": scenario_id,
                "title": title,
                "stage": stage,
                "status": "Error",
                "done_summary": "",
                "condensed_trace": f"[ERROR] {e}",
                "inner_ws": str(inner_ws),
                "missing_data_files": missing,
            })

        if viz_run_dir:
            completed = [{"id": r.get("scenario_id", ""), "title": r.get("title", "")[:40], "status": r.get("status", "")} for r in results]
            viz_emit_merge(viz_run_dir, {
                "inner": {
                    "batch": [{"id": s.get("scenario_id", ""), "title": str(s.get("title", ""))[:40]} for s in scenarios_batch],
                    "completed": completed,
                    "in_progress": None,
                },
            })

    return results
